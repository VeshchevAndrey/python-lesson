# Операторы сравнения — бинарные операторы, позволяющие сравнивать значения определённых типов данных, возвращая при этом чёткие ответы (True или False) на основе этих сравнений.
# True (Истина, логическое "да", 1) — положительный ответ 
# False (Ложь, логическое "нет", 0) — отрицательный ответ

# == (оператор равенства, возвращает True если значения полностью одинаковы, False — если значения отличаются)
number_1 = 4
number_2 = 5
print(number_1 == number_2)

number_1 = 4
number_2 = 4
print(number_1 == number_2)

print(type(number_1 == number_2))

number_1 = 4 # 100 в двоичной системе
number_2 = "4" # U+0032 в кодировке Unicode
print(number_1 == number_2)

number_1 = 4 # производится перевод в плавающую точку
number_2 = 4.0
print(number_1 == number_2)

number_1 = 4.1
number_2 = 4
print(number_1 == number_2)

string_1 = "привет"
string_2 = "Привет"
print(string_1 == string_2)

string_1 = "привет"
string_2 = "привет"
print(string_1 == string_2)

string_1 = "а"
string_2 = "a"
print(string_1 == string_2)

print("-" * 50)

# != (оператор неравенства, возвращает True если значения отличаются, False — если значения одинаковы)
number_1 = 4
number_2 = 5
print(number_1 != number_2)

number_1 = 4
number_2 = 4
print(number_1 != number_2)

string_1 = "привет"
string_2 = "Привет"
print(string_1 == string_2)

print("-" * 50)

# < (оператор "меньше, чем", возвращают True, если значение слева меньше, значения справа, False — в остальных случаях)
number_1 = 4
number_2 = 5
print(number_1 < number_2)

number_1 = 5
number_2 = 4
print(number_1 < number_2)

number_1 = 4
number_2 = 4
print(number_1 < number_2)

print("-" * 50)

# > (оператор "больше, чем", возвращают True, если значение слева больше, значения справа, False — в остальных случаях))
number_1 = 4
number_2 = 5
print(number_1 > number_2)

number_1 = 5
number_2 = 4
print(number_1 > number_2)

number_1 = 4
number_2 = 4
print(number_1 > number_2)

print("-" * 50)

# <= (оператор "меньше или равно", возвращают True, если значение слева меньше или равно значению справа, False — в ином случае)
