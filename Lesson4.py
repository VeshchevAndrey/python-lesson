# Условная конструкция — конструкция, позволяющая выполнять различные блоки команд в зависимости от истинности некоторого условия (условного выражения). Представляет собой реализацию ветвления в программе.
# if (условный оператор, ключевое слово "если")

# Шаблон простейшей условной конструкции:
# if <условное выражение, возвращающее ответ True или False>:
#     [блок команд, выполяемых в случае, если ответ на условное выражение был True]
#     ...

age = int(input("Введите свой возраст:"))
if age < 18:
	print("Доступ закрыт! Несоответствие возрастному ограничению!")

# Пример реализации условной конструкции
number_1 = int(input("Введи первое число:"))
number_2 = int(input("Введи второе число:"))
if number_1 > number_2:
	print("Ого, какой ты непоследовательный! Ввел первое число, а оно больше второго!")
	print("Не думал, что ты так сделаешь!")

# print("Продолжаем дальше. Эта строка будет выведена в любом случае.")

# Пример реализации условной конструкции 2
a = int(input("Целое число: "))
if a > 0:
    a = a + 1  
print("Полученное число:", a)

# else (ключевое слово "иначе/в любом другом случае", выполняет блоки кода при ложном ответе выражения)

# Шаблон дополненной условной конструкции:
# if <условное выражение, возвращающее ответ True или False>:
#     [блок команд, выполяемых в случае, если ответ на условное выражение был True]
#     ...
# else:
#     [блок команд, выполяемых в случае, если ответ на условное выражение был False]

