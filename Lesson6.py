# Методы проверки строки
# str.isupper() — определяет, состоит ли строка только из буквенных символов в верхнем регистре, в случае чего возвращает True, иначе False.
print("isupper() —", string.isupper())
# str.islower() — определяет, состоит ли строка только из буквенных символов в нижнем регистре, в случае чего возвращает True, иначе False.
print("islower() —", string.islower())
# str.istitle() — определяет, находится ли каждый первый буквенный символ в верхнем регистре, в случае чего возвращает True, иначе False.
print("istitle() —", string.istitle())
# str.isalnum() — определяет, состоит ли строка только из буквенных и/или числовых символов, в случае чего возвращает True, иначе False.
print("isalnum() —",string.isalnum())
# str.isdigit() — определяет, состоит ли строка только из числовых символов, в случае чего возвращает True, иначе False.
print("isdigit() —",string.isdigit())
# str.isalpha() — определяет, состоит ли строка только из буквенных символов, в случае чего возвращает True, иначе False.
print("isalpha() —",string.isalpha())
# str.isspace() — определяет, состоит ли строка только из пробельных символов (" ", "\n", "\t"), в случае чего возвращает True, иначе False.
print("isspace() —", string.isspace())

