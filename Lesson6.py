# Методы работы с подстроками
# Подстрока — последовательность символов, являющаяся частью другой строки. Последовательность символов может называться подстрокой только в том случае, когда она входит в строку в непрерывном виде.

string = "а роза упала на лапу азора"
# Методы поиска подстрок в строке
# str.count() — возвращает количество вхождений подстроки, переданной в качестве аргумента, в строку или её часть.
print("Пробелов —", string.count(" "))
print("а —", string.count("а"))
print("б —", string.count("б"))
print("роза —", string.count("роза"))
print("лапа —", string.count("лапа"))
print("роза —", string.count("роза"))
print("лапа —", string.count("лапа"))

