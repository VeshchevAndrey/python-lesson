# Последовательность — упорядоченный набор (коллекция) элементов, хранимый как единый объект, где к каждому элементу можно обратиться отдельно по его порядковому номеру (индексу). Для обращения используются квадратные скобки [], в которых указывается индекс нужного элемента.
# Индекс — номер элемента в последовательности. Начальный индекс — 0.

# Строка — упорядоченная неизменяемая последовательность, содержащие набор символов.

string = "привет"
print(string[0])
print(string[2])
print(string[5])
# print(string[6]) ошибка — выведен индекс больше максимального
