# Методы работы над строками
# Метод — функция, применяемая к конкретному типу данных (объектов), позволяющая проводить над ними определённые действия.

name = "андрей_вещев"
print(name)
# Единственный способ изменить существующую строку — перезаписать её
name = name.replace("_", " ").title()
print(name)

string = "Hello world!"
# Методы преобразования строки
# Регистр — вид написания буквенных символов. Различают верхний (заглавные буквы) и нижний (строчные буквы) регистры.
# str.upper() — возвращает строку, в которой все буквенные символы заменены своими аналогами в верхнем регистре.
print("upper() —", string.upper())
# str.lower() — возвращает строку, в которой все буквенные символы заменены своими аналогами в нижнем регистре.
print("lower() —", string.lower())
# str.title() — возвращает строку, в которой первый символ каждого слова (слова разделяются пробелами) преобразован в верхний регистр, остальные — в нижнем.
print("title() —", string.title())
# str.capitalize() — возвращает строку, в которой первый буквенный символ строки преобразован в верхний регистр, остальные — в нижнем
print("capitalize() —", string.capitalize())
# str.swapcase() — возвращает строку, в каждом буквенный символ примет противоположный изначальному регистр
print("swapcase() —", string.swapcase())

print(string) # методы преобразования не перезаписывают изначальную строку

