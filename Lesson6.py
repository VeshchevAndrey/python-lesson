# len() — функция, возвращающая количество элементов (длину) последовательности в виде целого числа.
string = "Мороз и солнце; день чудесный! Еще ты дремлешь, друг прелестный — Пора, красавица, проснись: Открой сомкнуты негой взоры Навстречу северной Авроры, Звездою севера явись!"
